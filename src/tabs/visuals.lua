-- Visuals tab: player ESP, police radar, robbery tags, loot ESP and car weak spots.
local UIS = game:GetService("UserInputService")
local ESP = __import("visuals/esp")
local Shops = __import("visuals/shops")
local LootESP = __import("visuals/lootesp")
local Route = __import("visuals/route")

return function(ctx)
	local win, safe, cycle = ctx.win, ctx.safe, ctx.cycle
	local tEsp = win:Tab("Visuals", { Section = "Combat", Icon = 3 })
	local mEsp = tEsp:Module({ Name = "Player ESP", Default = false, Callback = function(on) ESP.SetEnabled(on) end })
	mEsp:Section("Shapes")
	mEsp:Toggle({ Name = "Box", Default = ESP.Boxes, Callback = function(v) ESP.Boxes = v end })
	mEsp:Toggle({ Name = "Corner box style (off = full outline)", Default = ESP.CornerBox, Callback = function(v) ESP.CornerBox = v end })
	mEsp:Toggle({ Name = "Box fill (soft gradient)", Default = ESP.Fill, Callback = function(v) ESP.Fill = v end })
	mEsp:Toggle({ Name = "Dark outlines (easier to see)", Default = ESP.Outline, Callback = function(v) ESP.Outline = v end })
	mEsp:Toggle({ Name = "Skeleton", Default = ESP.Skeleton, Callback = function(v) ESP.Skeleton = v end })
	mEsp:Toggle({ Name = "Tracers", Default = ESP.Tracers, Callback = function(v) ESP.Tracers = v end })
	cycle(mEsp, "Tracer starts at", { "Bottom", "Centre", "Cursor" }, function() return ESP.TracerFrom end, function(v) ESP.TracerFrom = v end)
	cycle(mEsp, "Tracer ends at", { "Feet", "Body", "Head" }, function() return ESP.TracerTo end, function(v) ESP.TracerTo = v end)
	mEsp:Slider({ Name = "Tracer thickness", Min = 0.5, Max = 4, Step = 0.1, Default = ESP.TracerThickness, Callback = function(v) ESP.TracerThickness = v end })
	mEsp:Section("Info")
	mEsp:Toggle({ Name = "Name + role (police blue, fire red)", Default = ESP.Names, Callback = function(v) ESP.Names = v end })
	mEsp:Toggle({ Name = "Health bar", Default = ESP.Health, Callback = function(v) ESP.Health = v end })
	mEsp:Toggle({ Name = "Distance", Default = ESP.Distance, Callback = function(v) ESP.Distance = v end })
	mEsp:Toggle({ Name = "Held item (gun, tool)", Default = ESP.Tool, Callback = function(v) ESP.Tool = v end })
	mEsp:Slider({ Name = "Text size", Min = 10, Max = 18, Step = 1, Default = ESP.TextSize, Suffix = " px", Callback = function(v) ESP.SetTextSize(v) end })
	mEsp:Toggle({ Name = "Wanted tag (red)", Default = ESP.Wanted, Callback = function(v) ESP.Wanted = v end })
	mEsp:Toggle({ Name = "Wanted stars + bounty (instead of the word WANTED)", Default = ESP.Stars, Callback = function(v) ESP.Stars = v end })
	mEsp:Toggle({ Name = "Car health next to the distance", Default = ESP.CarInfo, Callback = function(v) ESP.CarInfo = v end })
	mEsp:Toggle({ Name = "Hover card (point at a player)", Default = ESP.Hover, Callback = function(v) ESP.Hover = v end })
	mEsp:Section("Range")
	mEsp:Slider({ Name = "Max distance", Min = 100, Max = 3000, Step = 50, Default = ESP.MaxDist, Suffix = " st", Callback = function(v) ESP.MaxDist = v end })
	mEsp:Toggle({ Name = "Fade with distance", Default = ESP.Fade, Callback = function(v) ESP.Fade = v end })
	mEsp:Section("Who to show")
	mEsp:Toggle({ Name = "Show police", Default = true, Callback = function(v) ESP.Teams.Police = v end })
	mEsp:Toggle({ Name = "Show fire department", Default = true, Callback = function(v) ESP.Teams.FireDepartment = v end })
	mEsp:Toggle({ Name = "Show citizens", Default = true, Callback = function(v) ESP.Teams.Citizen = v end })
	mEsp:Toggle({ Name = "Show other jobs / prisoners", Default = true, Callback = function(v) ESP.Teams.Other = v end })
	local mRadar = tEsp:Module({ Name = "Police radar (escape helper)", Default = true, Callback = function(on) ESP.Radar = on end })
	mRadar:Slider({ Name = "Warn within", Min = 100, Max = 800, Step = 25, Default = ESP.RadarDist, Suffix = " st", Callback = function(v) ESP.RadarDist = v end })
	local mShops = tEsp:Module({ Name = "Robbery tags (shops, bank, club)", Default = false, Callback = function(on) Shops.SetEnabled(on) end })
	mShops:Label({ Name = "Shows", Value = "ready / cooldown / alarm + risk" })
	mShops:Slider({ Name = "Show within", Min = 100, Max = 1500, Step = 50, Default = Shops.MaxDist, Suffix = " st", Callback = function(v) Shops.MaxDist = v end })
	mShops:Toggle({ Name = "Risk line (police online, nearest police)", Default = Shops.Risk, Callback = function(v) Shops.Risk = v end })
	mShops:Toggle({ Name = "Only places that are ready", Default = false, Callback = function(v) Shops.OnlyReady = v end })
	Shops.PoliceFn = ESP.PolicePositions
	safe("shops", Shops.Start)
	-- MONEY ROUTE: a glowing line along the roads to the best robbery that is ready right now
	local mRoute = tEsp:Module({ Name = "Money route (line to the best ready robbery)", Default = false, Callback = function(on) Route.SetEnabled(on) end })
	local lRoute = mRoute:Label({ Name = "Going to", Value = "off" })
	mRoute:Choice({ Name = "Pick", Options = Route.Modes, Default = Route.Mode, Callback = function(v) Route.Mode = v end })
	mRoute:Toggle({ Name = "Skip high-risk places (police close / alarm)", Default = Route.SkipRisky, Callback = function(v) Route.SkipRisky = v end })
	mRoute:Section("Look")
	mRoute:ColorPicker({ Name = "Line colour", Default = Route.Color, Callback = function(c, final) Route.Color = c; if final then Route.Restyle() end end })
	mRoute:ColorPicker({ Name = "Colour at the target", Default = Route.EndColor, Callback = function(c, final) Route.EndColor = c; if final then Route.Restyle() end end })
	mRoute:Slider({ Name = "Line width", Min = 0.4, Max = 3, Step = 0.1, Default = Route.Width, Callback = function(v) Route.Width = v; Route.Restyle() end })
	mRoute:Toggle({ Name = "Light pillar on the target", Default = Route.Pillar, Callback = function(v) Route.Pillar = v end })
	mRoute:Toggle({ Name = "Target + distance at the top of the screen", Default = Route.Hud, Callback = function(v) Route.Hud = v end })
	Route.Notify = function(m) win:Notify(m, 3) end
	safe("route", Route.Start)
	task.spawn(function()
		while ctx.alive() do
			task.wait(1)
			pcall(function() lRoute:Set(Route.TargetText()) end)
		end
	end)
	local mLoot2 = tEsp:Module({ Name = "Loot ESP (money, items, drops)", Default = false, Callback = function(on) LootESP.SetEnabled(on) end })
	mLoot2:Label({ Name = "Shows", Value = "what each pile is worth" })
	mLoot2:Slider({ Name = "Show within", Min = 30, Max = 800, Step = 10, Default = LootESP.MaxDist, Suffix = " st", Callback = function(v) LootESP.MaxDist = v end })
	mLoot2:Toggle({ Name = "Money piles", Default = LootESP.Money, Callback = function(v) LootESP.Money = v; LootESP.Rescan() end })
	mLoot2:Toggle({ Name = "Items to steal", Default = LootESP.Items, Callback = function(v) LootESP.Items = v; LootESP.Rescan() end })
	mLoot2:Toggle({ Name = "Dropped cash / items", Default = LootESP.Drops, Callback = function(v) LootESP.Drops = v; LootESP.Rescan() end })
	mLoot2:Toggle({ Name = "Only piles that are active", Default = LootESP.OnlyEnabled, Callback = function(v) LootESP.OnlyEnabled = v end })
	safe("lootesp", LootESP.Start)
	local mSpot = tEsp:Module({ Name = "Car weak spots (where to hit)", Default = false, Callback = function(on) ESP.Spots = on end })
	mSpot:Label({ Name = "Marks", Value = "tyres, engine, fuel tank" })
	mSpot:Slider({ Name = "Show within", Min = 60, Max = 500, Step = 10, Default = ESP.SpotDist, Suffix = " st", Callback = function(v) ESP.SpotDist = v end })
	mSpot:Toggle({ Name = "Only cars of wanted players", Default = false, Callback = function(v) ESP.SpotsWantedOnly = v end })
	ESP.OnPolice = function(d) win:Notify(("Police nearby: %d studs"):format(d), 4) end
	safe("esp", ESP.Start)

end
